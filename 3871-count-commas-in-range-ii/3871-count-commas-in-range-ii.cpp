class Solution {
public:
    long long countCommas(long long n) {
        if(n<1000) return 0;
        if(1000 <= n && n <= 999999)
            return n - 999;

        if(1000000 <= n && n <= 999999999)
            return (n-999)+(n - 999999);

        if(1000000000 <= n && n <= 999999999999)
            return (n-999)+(n - 999999)+ (n - 999999999);

        if(1000000000000 <= n && n <= 999999999999999)
            return (n-999)+(n - 999999)+ (n - 999999999)+(n - 999999999999);

        if(1000000000000000 <= n)
            return (n-999)+(n - 999999)+ (n - 999999999)+(n - 999999999999)+ (n - 999999999999999);
        return 0;
        
    }
};